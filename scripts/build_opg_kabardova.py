def sphere_for_item(n: int) -> str:
    return SPHERES[(n - 1) % len(SPHERES)]


def option_block(sphere: str, dim: str) -> dict:
    skill = f"{sphere}_skill"
    att = f"{sphere}_att"
    wish = f"{sphere}_wish"
    if dim == "skill":
        return {
            "1": ["2 — делаю, как правило, хорошо", {skill: 2}],
            "2": ["1 — делаю средне", {skill: 1}],
            "3": ["0 — делаю плохо (совсем не умею)", {skill: 0}],
        }
    if dim == "att":
        return {
            "1": ["2 — положительные (приятно, интересно, легко)", {att: 2}],
            "2": ["1 — нейтральные (всё равно)", {att: 1}],
            "3": ["0 — отрицательные (неприятно, неинтересно)", {att: 0}],
        }
    return {
        "1": ["2 — да", {wish: 2}],
        "2": ["1 — всё равно", {wish: 1}],
        "3": ["0 — нет", {wish: 0}],
    }


def build() -> list:
    assert len(STATEMENTS) == OPG_N
    out: list = []
    for i, body in enumerate(STATEMENTS, start=1):
        sp = sphere_for_item(i)
        for dim, title, qline in [
            ("skill", "Оценка: умение (1).", "Насколько хорошо вы умеете делать это?"),
            ("att", "Оценка: отношение (2).", "Какие ощущения вы испытывали, когда делали это?"),
            ("wish", "Оценка: желание (3).", "Хотели бы вы делать это в вашей будущей работе?"),
        ]:
            head_intro = FULL_INTRO if i == 1 and dim == "skill" else SHORT_HEAD.format(n=i, sphere=sp)
            if dim == "skill":
                qtext = f"{head_intro}{body}\n\n{title}\n{qline}{NEVER_NOTE}"
            else:
                qtext = (
                    f"{head_intro}"
                    "То же высказывание, что в предыдущем сообщении (не повторяем текст).\n\n"
                    f"{title}\n{qline}{NEVER_NOTE_FOLLOWUP}"
                )
            out.append(
                {
                    "q": qtext,
                    "opg_item": i,
                    "opg_dim": dim,
                    "options": option_block(sp, dim),
                }
            )
    return out


def main():
    data = build()
    assert len(data) == OPG_N * 3
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"Wrote {len(data)} steps to {OUT}")


if __name__ == "__main__":
    main()
