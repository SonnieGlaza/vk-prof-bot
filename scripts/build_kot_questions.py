def qq(num: int, text: str, choices: list[tuple[int, str]], correct: int) -> dict:
    options: dict[str, list] = {}
    for key, label in choices:
        w = {"LOGIC": 1} if key == correct else {}
        options[str(key)] = [label, w]
    return {"q": f"{num}. {text}", "options": options}


